const UI_LANGS = Object.keys(I18N);
let LANG = "en";
try {
  const saved = localStorage.getItem("uiLang");
  if (UI_LANGS.includes(saved)) LANG = saved;
} catch (e) { /* storage blocked → default */ }

// T("cut.added", {name: "Clip 1", len: "0:30.0"}) → string in the current UI language.
function T(key, params) {
  const s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  document.title = T("app.title");
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = T(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = T(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = T(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = T(el.dataset.i18nPlaceholder); });
}
function setUiLang(lang) {
  if (!UI_LANGS.includes(lang)) return;
  LANG = lang;
  try { localStorage.setItem("uiLang", lang); } catch (e) { /* ignore */ }
  applyI18n();
}
